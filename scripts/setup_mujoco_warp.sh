#!/usr/bin/env bash
# Fixed fork revision with the analytic adjoint and COM changes already committed.
#   bash scripts/setup_mujoco_warp.sh [DEST] [--no-install]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/third_party/mujoco_warp_fork"
INSTALL=1
DEST_SET=0
for arg in "$@"; do
  case "$arg" in
    --no-install) INSTALL=0 ;;
    -h|--help)
      echo 'Usage: bash scripts/setup_mujoco_warp.sh [DEST] [--no-install]'
      echo 'Default DEST: third_party/mujoco_warp_fork; existing checkouts must already match the fixed revision.'
      exit 0 ;;
    -*) echo "Unknown option: $arg" >&2; exit 2 ;;
    *)
      [[ "$DEST_SET" == 0 ]] || { echo 'Only one destination is accepted' >&2; exit 2; }
      DEST="$arg"; DEST_SET=1 ;;
  esac
done

PY="${PYTHON:-python}"
URL=https://github.com/LingzheZhao/mujoco_warp.git
SDK_REVISION=d39d6ad691e63ce94e66df69d509eff42047c2d9
[[ "$SDK_REVISION" =~ ^[0-9a-f]{40}$ ]] || {
  echo 'setup_mujoco_warp.sh must declare the fixed fork commit before use' >&2; exit 1; }

if [[ -e "$DEST" || -L "$DEST" ]]; then
  [[ -d "$DEST/.git" || -f "$DEST/.git" ]] || {
    echo "$DEST exists without its own Git checkout; use a fresh directory" >&2; exit 1; }
  [[ "$(git -C "$DEST" rev-parse HEAD)" == "$SDK_REVISION" ]] || {
    echo "$DEST is not at the fixed fork revision; use a fresh directory" >&2; exit 1; }
else
  mkdir -p "$(dirname "$DEST")"
  git clone -q --filter=blob:none --no-checkout -- "$URL" "$DEST"
  git -C "$DEST" cat-file -e "$SDK_REVISION^{commit}" 2>/dev/null || \
    git -C "$DEST" fetch -q origin "$SDK_REVISION"
  git -C "$DEST" -c advice.detachedHead=false checkout -q --detach "$SDK_REVISION"
fi

# Compare the complete committed tree, including installation metadata and data
# resources. Ignore only Git internals, Python bytecode and setuptools metadata
# generated by editable installation. Unexpected source/resource files fail.
REFERENCE="$(mktemp -d)"
trap 'rm -rf -- "$REFERENCE"' EXIT
git -C "$DEST" archive "$SDK_REVISION" | tar -x -C "$REFERENCE"
diff -qr --no-dereference --exclude='.git' --exclude='__pycache__' --exclude='*.pyc' \
  --exclude='mujoco_warp.egg-info' -- "$REFERENCE" "$DEST" || {
  echo "$DEST differs from the fixed fork tree; use a fresh directory" >&2; exit 1; }
echo "MuJoCo Warp fixed fork tree OK: $DEST ($SDK_REVISION)"
if [[ "$INSTALL" == 1 ]]; then
  "$PY" -m pip install --no-deps -e "$DEST"
fi
